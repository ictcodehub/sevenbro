export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  const entry = STRINGS[key]
  const raw = entry[lang] ?? entry.id
  if (!vars) return raw
  return raw.replace(/\{\{(\w+)\}\}/g, (_, k) => String(vars[k] ?? `{{${k}}}`))
}
